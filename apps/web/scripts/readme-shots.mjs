// Captures README screenshots from the running demo (dark theme). Usage: node scripts/readme-shots.mjs
import { chromium } from "@playwright/test";
const out = "../../docs/screenshots", base = process.env.BASE_URL ?? "http://localhost:3100";
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2, colorScheme: "dark" });
const page = await ctx.newPage();
await page.addInitScript(() => { try { localStorage.setItem("openkg-theme", "dark"); } catch {} });
await page.goto(base + "/login");
await page.getByRole("button", { name: /Enter demo/ }).click();
await page.waitForURL(base + "/");
await page.waitForTimeout(1500);
// The library is not captured: a real workspace also lists private research graphs.
await page.getByRole("link", { name: "Open Series B product leaders" }).click();
await page.waitForSelector(".react-flow__node");
await page.waitForTimeout(1200);
await page.getByRole("link", { name: /^Review/ }).click();
await page.getByRole("tab", { name: "By type" }).click();
await page.getByRole("button", { name: /Conflict on Quillon Data/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/review.png` });
await page.getByRole("link", { name: /^Changes/ }).click();
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/changes.png` });
await page.getByRole("navigation", { name: "Graph sections" }).getByRole("link", { name: "Table" }).click();
await page.getByRole("tab", { name: "Company" }).click();
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/table.png` });
await page.getByRole("link", { name: "Graph", exact: true }).click();
await page.waitForSelector(".react-flow__node");
await page.getByRole("button", { name: /Start research/ }).click();
await page.getByRole("button", { name: "Start simulation" }).click();
await page.waitForTimeout(7000);
await page.screenshot({ path: `${out}/canvas-live.png` });
await page.getByRole("navigation", { name: "Graph sections" }).getByRole("link", { name: "Research" }).click();
await page.waitForTimeout(3000);
await page.screenshot({ path: `${out}/mission-control.png` });
await page.waitForFunction(() => /Awaiting review|Completed/.test(document.querySelector("header")?.parentElement?.innerText ?? "") && !document.body.innerText.includes("Working"), null, { timeout: 120000 });
await page.getByRole("link", { name: "Graph", exact: true }).click();
await page.waitForSelector(".react-flow__node");
await page.locator('.react-flow__node[aria-label="Company Quillon Data"]').click();
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/evidence-lens.png` });
await browser.close();
console.log("screenshots written to docs/screenshots");
